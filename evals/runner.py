"""Executes every scenario in evals/scenarios.py against the real Agent +
mock ProviderAPI (no live model), and generates:

  - eval_table.md   (scenario · expected · actual · pass/fail · notes)
  - eval_results.json (machine-readable form of the same)

Run with: python -m evals.runner
Exits non-zero if any scenario fails, so it's CI-able.
"""
from __future__ import annotations

import json
import shutil
import sys
import tempfile
import time
import traceback
from pathlib import Path

from evals.scenarios import SCENARIOS

REPO_ROOT = Path(__file__).resolve().parents[1]


def run_all() -> list:
    results = []
    for spec in SCENARIOS:
        workspace = Path(tempfile.mkdtemp(prefix="eval_"))
        t0 = time.monotonic()
        try:
            actual = spec["fn"](workspace)
            results.append({
                "name": spec["name"], "description": spec["description"],
                "expected": spec["expected"], "actual": actual or "ok",
                "passed": True, "notes": "", "elapsed_ms": round((time.monotonic() - t0) * 1000, 1),
            })
        except AssertionError as e:
            results.append({
                "name": spec["name"], "description": spec["description"],
                "expected": spec["expected"], "actual": f"ASSERTION FAILED: {e}",
                "passed": False, "notes": "invariant violated", "elapsed_ms": round((time.monotonic() - t0) * 1000, 1),
            })
        except Exception as e:
            results.append({
                "name": spec["name"], "description": spec["description"],
                "expected": spec["expected"], "actual": f"{type(e).__name__}: {e}",
                "passed": False, "notes": traceback.format_exc(limit=3),
                "elapsed_ms": round((time.monotonic() - t0) * 1000, 1),
            })
        finally:
            shutil.rmtree(workspace, ignore_errors=True)
    return results


def write_markdown_table(results: list, path: Path) -> None:
    lines = [
        "# Eval Results",
        "",
        f"Generated by `python -m evals.runner` -- {len(results)} scenarios, "
        f"{sum(1 for r in results if r['passed'])} passed, "
        f"{sum(1 for r in results if not r['passed'])} failed.",
        "",
        "| # | Scenario | Expected | Actual | Pass/Fail | Notes |",
        "|---|----------|----------|--------|-----------|-------|",
    ]
    for i, r in enumerate(results, start=1):
        status = "PASS" if r["passed"] else "**FAIL**"
        notes = r["notes"].replace("\n", " ").replace("|", "\\|")[:200]
        expected = r["expected"].replace("|", "\\|")
        actual = str(r["actual"]).replace("\n", " ").replace("|", "\\|")[:300]
        lines.append(f"| {i} | `{r['name']}` | {expected} | {actual} | {status} | {notes} |")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> int:
    results = run_all()
    write_markdown_table(results, REPO_ROOT / "eval_table.md")
    (REPO_ROOT / "eval_results.json").write_text(json.dumps(results, indent=2), encoding="utf-8")

    passed = sum(1 for r in results if r["passed"])
    failed = len(results) - passed
    print(f"{passed}/{len(results)} scenarios passed.")
    if failed:
        print(f"{failed} FAILED:")
        for r in results:
            if not r["passed"]:
                print(f"  - {r['name']}: {r['actual']}")
    print(f"Wrote {REPO_ROOT / 'eval_table.md'}")
    print(f"Wrote {REPO_ROOT / 'eval_results.json'}")
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
